// lockRoomForUser loads only the room and the actor's membership. The caller
// holds the rooms row lock until the surrounding mutation transaction commits.
// The returned room is a validation projection and must never be passed to Save.
func (r *GormRoomRepository) lockRoomForUser(ctx context.Context, id model.RoomID, user model.UserID) (*model.Room, error) {
	db := gormDB(ctx, r.db)
	var row dbmodel.Room
	err := db.Clauses(clause.Locking{Strength: "UPDATE"}).Where("room_id = ?", id.String()).First(&row).Error
	if errors.Is(err, gorm.ErrRecordNotFound) {
		return nil, ErrRoomNotFound
	}
	if err != nil {
		return nil, err
	}
	room, err := roomFromRow(row)
	if err != nil {
		return nil, err
	}
	var participants []dbmodel.RoomParticipant
	if err := db.Where("room_id = ? AND user_id = ?", id.String(), string(user)).Find(&participants).Error; err != nil {
		return nil, err
	}
	for _, p := range participants {
		room.Participants = append(room.Participants, model.Participant{UserID: user, JoinedAt: p.JoinedAt})
	}
	var admins int64
	if err := db.Model(&dbmodel.RoomAdmin{}).Where("room_id = ? AND user_id = ?", id.String(), string(user)).Count(&admins).Error; err != nil {
		return nil, err
	}
	if admins > 0 {
		room.Settings.Admins = []model.UserID{user}
	}
	return room, nil
}

// AppendMessage validates through the domain model and inserts a single row.
// WithinTransaction reuses the service's transaction when present.
func (r *GormRoomRepository) AppendMessage(ctx context.Context, id model.RoomID, message model.Message) error {
	return NewGormTransactionRunner(r.db).WithinTransaction(ctx, func(ctx context.Context) error {
		room, err := r.lockRoomForUser(ctx, id, message.Author)
		if err != nil {
			return err
		}
		if _, err := room.PostMessage(message.Author, message.Content, message.CreatedAt, message.MessageID); err != nil {
			return err
		}
		db := gormDB(ctx, r.db)
		row := dbmodel.RoomMessage{MessageID: messageIDString(message.MessageID), RoomID: id.String(), AuthorUserID: string(message.Author), Content: message.Content, CreatedAt: message.CreatedAt}
		if err := db.Create(&row).Error; err != nil {
			return err
		}
		return db.Model(&dbmodel.Room{}).Where("room_id = ?", id.String()).Update("updated_at", message.CreatedAt).Error
	})
}

// JoinParticipant preserves Join's idempotency, including after game start.
// Cards are generated by StartGame, not Join.
func (r *GormRoomRepository) JoinParticipant(ctx context.Context, id model.RoomID, user model.UserID, now time.Time) (joined bool, count int, err error) {
	err = NewGormTransactionRunner(r.db).WithinTransaction(ctx, func(ctx context.Context) error {
		room, err := r.lockRoomForUser(ctx, id, user)
		if err != nil {
			return err
		}
		if room.IsParticipant(user) {
			return nil
		}
		if err := room.Join(user, now); err != nil {
			return err
		}
		if err := validateUserID(user); err != nil {
			return err
		}
		db := gormDB(ctx, r.db)
		// An admin may already have a room_users row; preserve that row unchanged.
		row := dbmodel.RoomUser{RoomID: id.String(), UserID: string(user), UserName: string(user), CreatedAt: now, UpdatedAt: now}
		if err := db.Clauses(clause.OnConflict{DoNothing: true}).Create(&row).Error; err != nil {
			return err
		}
		participant := dbmodel.RoomParticipant{RoomID: id.String(), UserID: string(user), JoinedAt: now}
		if err := db.Create(&participant).Error; err != nil {
			return err
		}
		if err := db.Model(&dbmodel.Room{}).Where("room_id = ?", id.String()).Update("updated_at", now).Error; err != nil {
			return err
		}
		var total int64
		if err := db.Model(&dbmodel.RoomParticipant{}).Where("room_id = ?", id.String()).Count(&total).Error; err != nil {
			return err
		}
		joined, count = true, int(total)
		return nil
	})
	if err != nil {
		return false, 0, err
	}
	return joined, count, nil
}

// LockPickRoom is a validation projection, never suitable for Save. Picked balls
// are bounded by 75 and are needed by StartPick's exhaustion validation.
func (r *GormRoomRepository) LockPickRoom(ctx context.Context, id model.RoomID, actor model.UserID) (*model.Room, error) {
	room, err := r.lockRoomForUser(ctx, id, actor)
	if err != nil {
		return nil, err
	}
	if err := loadPickedBalls(gormDB(ctx, r.db), []string{id.String()}, map[string]*model.Room{id.String(): room}); err != nil {
		return nil, err
	}
	return room, nil
}

func (r *GormRoomRepository) UpdatePickState(ctx context.Context, room *model.Room) error {
	return gormDB(ctx, r.db).Model(&dbmodel.Room{}).Where("room_id = ?", room.RoomID.String()).Updates(map[string]any{"pick_state": string(room.PickState), "updated_at": gormDB(ctx, r.db).NowFunc()}).Error
}

func (r *GormRoomRepository) UpdateQRCode(ctx context.Context, room *model.Room) error {
	return gormDB(ctx, r.db).Model(&dbmodel.Room{}).Where("room_id = ?", room.RoomID.String()).Updates(map[string]any{"qr_code_visible": room.QrCodeVisible, "updated_at": gormDB(ctx, r.db).NowFunc()}).Error
}

// SaveFinishedPick persists the delta produced by Room.FinishPick. The caller
// must hold the room lock in the same transaction as the aggregate read.
func (r *GormRoomRepository) SaveFinishedPick(ctx context.Context, before model.Room, room *model.Room) error {
	db := gormDB(ctx, r.db)
	id := room.RoomID.String()
	ball := dbmodel.RoomPickedBall{PickedBallID: uuid.NewString(), RoomID: id, PickOrder: uint16(len(room.PickedBalls)), Number: uint8(room.PickedBalls[len(room.PickedBalls)-1]), PickedAt: room.UpdatedAt}
	if err := db.Create(&ball).Error; err != nil {
		return err
	}
	cardIDs := make(map[model.UserID]string, len(room.Cards))
	for i, card := range room.Cards {
		cardID := cardIDString(card.CardID)
		cardIDs[card.OwnerUserID] = cardID
		for j, cell := range card.Cells {
			if cell.CellState == before.Cards[i].Cells[j].CellState {
				continue
			}
			if err := db.Model(&dbmodel.RoomCardCell{}).Where("card_id = ? AND cell_index = ?", cardID, uint8(cell.Index)).Update("cell_state", string(cell.CellState)).Error; err != nil {
				return err
			}
		}
	}
	bingos := make([]dbmodel.RoomBingoRecord, 0)
	for _, record := range room.BingoRecords[len(before.BingoRecords):] {
		bingos = append(bingos, dbmodel.RoomBingoRecord{RecordID: recordIDString(record.RecordID), RoomID: id, UserID: string(record.UserID), CardID: cardIDs[record.UserID], LineIndex: uint8(record.Line), BingoOrder: uint(record.Order), CreatedAt: record.CreatedAt})
	}
	if err := createInBatches(db, bingos); err != nil {
		return err
	}
	reaches := make([]dbmodel.RoomReachRecord, 0)
	for _, record := range room.ReachRecords[len(before.ReachRecords):] {
		reaches = append(reaches, dbmodel.RoomReachRecord{RecordID: recordIDString(record.RecordID), RoomID: id, UserID: string(record.UserID), LineIndex: uint8(record.Line), LastCellIndex: uint8(record.LastCellIndex), CreatedAt: record.CreatedAt})
	}
	if err := createInBatches(db, reaches); err != nil {
		return err
	}
	return r.UpdatePickState(ctx, room)
}

// LockRoomForUser loads only row metadata and actor membership for validation.
func (r *GormRoomRepository) LockRoomForUser(ctx context.Context, id model.RoomID, actor model.UserID) (*model.Room, error) {
	return r.lockRoomForUser(ctx, id, actor)
}
